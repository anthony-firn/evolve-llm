"""Generate src/iq_tables.rs from ggml's ggml-common.h (MIT, the ggml authors).

Usage: python3 tools/gen_iq_tables.py /path/to/llama.cpp/ggml/src/ggml-common.h
"""
import re
import sys
from pathlib import Path

TABLES = [("iq2xxs_grid", "u64"), ("iq2xs_grid", "u64"), ("iq2s_grid", "u64"),
          ("iq3xxs_grid", "u32"), ("iq3s_grid", "u32"), ("iq1s_grid", "u64")]


def main():
    src = Path(sys.argv[1]).read_text()
    out = ["//! Code books of ggml's IQ formats, generated by tools/gen_iq_tables.py from ggml-common.h.",
           "//! Copyright (c) 2023-2026 The ggml authors. MIT License; see NOTICE.", ""]
    for name, ty in TABLES:
        m = re.search(rf"GGML_TABLE_BEGIN\(\w+, {name}, (\w+)\)(.*?)GGML_TABLE_END", src, re.S)
        values = re.findall(r"0x[0-9a-fA-F]+", m.group(2))
        out.append(f"pub static {name.upper()}: [{ty}; {len(values)}] = [")
        for i in range(0, len(values), 8):
            out.append("    " + ", ".join(v.lower() for v in values[i:i + 8]) + ",")
        out.append("];")
        out.append("")
    Path(__file__).resolve().parents[1].joinpath("src/iq_tables.rs").write_text("\n".join(out))
    print("wrote", ", ".join(f"{n}" for n, _ in TABLES))


if __name__ == "__main__":
    main()
